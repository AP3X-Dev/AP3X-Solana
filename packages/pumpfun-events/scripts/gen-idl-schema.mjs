// Generates src/generated/idl-schema.ts from the vendored IDLs in ../idl.
// Keeps every event (plus the types they reference) and the instructions and
// account layouts the pumpfun-protocol builders and state readers use. Run: pnpm gen:idl
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const hex = (a) => Buffer.from(a).toString('hex');
// Docs are dropped to keep the generated module small.
const stripDocs = (v) => JSON.parse(JSON.stringify(v, (k, x) => (k === 'docs' ? undefined : x)));

const PROGRAMS = [
  {
    key: 'pump',
    file: 'pump.json',
    instructions: ['create', 'create_v2', 'buy', 'buy_exact_sol_in', 'sell'],
    accounts: ['BondingCurve', 'Global'],
  },
  {
    key: 'pumpAmm',
    file: 'pump_amm.json',
    instructions: ['buy', 'buy_exact_quote_in', 'sell'],
    accounts: ['Pool', 'GlobalConfig'],
  },
];

function collectDefined(type, out) {
  if (!type || typeof type !== 'object') return;
  if (type.defined) out.add(type.defined.name);
  for (const v of Object.values(type)) collectDefined(v, out);
}

const schema = {};
for (const p of PROGRAMS) {
  const idl = JSON.parse(readFileSync(join(root, 'idl', p.file), 'utf8'));
  const types = new Map(idl.types.map((t) => [t.name, t]));
  const needed = new Set();
  const events = idl.events.map((e) => {
    const t = types.get(e.name);
    if (!t) throw new Error(`${p.file}: event ${e.name} has no type`);
    collectDefined(t.type, needed);
    return { name: e.name, discriminator: hex(e.discriminator), fields: t.type.fields };
  });
  const accounts = p.accounts.map((name) => {
    const a = idl.accounts.find((x) => x.name === name);
    const t = types.get(name);
    if (!a || !t) throw new Error(`${p.file}: account ${name} missing`);
    collectDefined(t.type, needed);
    return { name, discriminator: hex(a.discriminator), fields: t.type.fields };
  });
  // Close over nested defined types.
  let grew = true;
  while (grew) {
    grew = false;
    for (const n of [...needed]) {
      const before = needed.size;
      collectDefined(types.get(n)?.type, needed);
      if (needed.size !== before) grew = true;
    }
  }
  const instructions = p.instructions.map((name) => {
    const ix = idl.instructions.find((i) => i.name === name);
    if (!ix) throw new Error(`${p.file}: instruction ${name} missing`);
    for (const a of ix.args) collectDefined(a.type, needed);
    return {
      name,
      discriminator: hex(ix.discriminator),
      accounts: ix.accounts.map((a) => ({
        name: a.name,
        writable: Boolean(a.writable),
        signer: Boolean(a.signer),
        ...(a.address ? { address: a.address } : {}),
        ...(a.pda ? { pda: a.pda } : {}),
        ...(a.optional ? { optional: true } : {}),
      })),
      args: ix.args,
    };
  });
  schema[p.key] = {
    address: idl.address,
    events,
    accounts,
    types: Object.fromEntries([...needed].sort().map((n) => [n, types.get(n).type])),
    instructions,
  };
}

for (const k of Object.keys(schema)) schema[k] = stripDocs(schema[k]);

const out = `// Generated by scripts/gen-idl-schema.mjs from idl/*.json. Do not edit.
import type { IdlProgramSchema } from '../idl-types.js';

export const PUMP_SCHEMA: IdlProgramSchema = ${JSON.stringify(schema.pump)};

export const PUMP_AMM_SCHEMA: IdlProgramSchema = ${JSON.stringify(schema.pumpAmm)};
`;
writeFileSync(join(root, 'src', 'generated', 'idl-schema.ts'), out);
console.log(`wrote src/generated/idl-schema.ts (${out.length} bytes)`);
